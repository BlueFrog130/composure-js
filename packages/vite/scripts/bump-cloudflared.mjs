// Pins the cloudflared release the Dev Loop downloads when none is installed (ADR 0031), and
// regenerates src/cloudflared-release.ts: each platform's asset and the SHA-256 of its bytes.
//   node scripts/bump-cloudflared.mjs [version]   (default: the latest release)
// Every asset is downloaded and hashed here; GitHub's own digest, when it lists one, must agree.
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";

const repo = "cloudflare/cloudflared";

/** `${process.platform}-${process.arch}` → the release asset it runs. */
const TARGETS = {
  "darwin-arm64": "cloudflared-darwin-arm64.tgz",
  "darwin-x64": "cloudflared-darwin-amd64.tgz",
  "linux-arm": "cloudflared-linux-arm",
  "linux-arm64": "cloudflared-linux-arm64",
  "linux-ia32": "cloudflared-linux-386",
  "linux-x64": "cloudflared-linux-amd64",
  // No arm64 build for Windows: Windows on Arm runs the x64 one.
  "win32-arm64": "cloudflared-windows-amd64.exe",
  "win32-ia32": "cloudflared-windows-386.exe",
  "win32-x64": "cloudflared-windows-amd64.exe",
};

const tag = process.argv[2];
const api = `https://api.github.com/repos/${repo}/releases/${tag ? `tags/${tag}` : "latest"}`;
const response = await fetch(api, { headers: { accept: "application/vnd.github+json" } });
if (!response.ok) throw new Error(`Fetching ${api} failed: ${response.status}`);
const release = await response.json();
const version = release.tag_name;

const hashes = new Map();
for (const file of new Set(Object.values(TARGETS))) {
  const listed = release.assets.find((asset) => asset.name === file);
  if (!listed) throw new Error(`cloudflared ${version} has no ${file}`);
  const download = await fetch(`https://github.com/${repo}/releases/download/${version}/${file}`);
  if (!download.ok) throw new Error(`Downloading ${file} failed: ${download.status}`);
  const sha256 = createHash("sha256")
    .update(new Uint8Array(await download.arrayBuffer()))
    .digest("hex");
  if (listed.digest && listed.digest !== `sha256:${sha256}`) throw new Error(`${file} hashes to ${sha256}, but GitHub lists ${listed.digest}`);
  hashes.set(file, sha256);
  console.log(`${file} ${sha256}`);
}

const entries = Object.entries(TARGETS)
  .map(([target, file]) => `    "${target}": { file: "${file}", sha256: "${hashes.get(file)}" },`)
  .join("\n");
writeFileSync(
  new URL("../src/cloudflared-release.ts", import.meta.url),
  `// Generated by \`node packages/vite/scripts/bump-cloudflared.mjs [version]\`: never edit by hand.

/** A cloudflared release, and the asset for each \`\${process.platform}-\${process.arch}\` with its SHA-256. */
export interface CloudflaredRelease {
  version: string
  assets: Partial<Record<string, { file: string; sha256: string }>>
}

/** The cloudflared release the Dev Loop downloads when none is installed. */
export const CLOUDFLARED_RELEASE: CloudflaredRelease = {
  version: "${version}",
  assets: {
${entries}
  },
}
`,
);
console.log(`Pinned cloudflared ${version}`);
